export const COMPONENT_SPRITES: string[] = ['wind', 'solar', 'battery', 'controller', 'sales', 'sales2', 'research', 'research2', 'core', 'thorium', 'fusion', 'generator', 'generator2', 'cooler', 'exchanger', 'pipe', 'pipe2', 'accumulator']
export const PROPOSED_SPRITES: string[] = ['insulator']

/** Tamaños de rejilla admitidos. 16 es el arte viejo; 32 es el actual. */
const SPRITE_SIZES = [16, 32]

export function validate(): void {
  for (const [name, rows] of Object.entries(SPRITES)) {
    if (!SPRITE_SIZES.includes(rows.length)) throw new Error(`${name}: ${rows.length} filas`)
    rows.forEach((row, y) => {
      if (row.length !== rows.length) throw new Error(`${name} fila ${y}: ${row.length} columnas, se esperaban ${rows.length}`)
      for (const ch of row) if (ch !== '.' && !(ch in PALETTE)) throw new Error(`${name} fila ${y}: color desconocido "${ch}"`)
    })
  }
  // El terreno tiene que ir todo a la misma resolución: el autotiler mezcla
  // los tres sprites en un mismo tile.
  const sizes = new Set(TERRAIN_KINDS.concat('shore' as TerrainKind).map((k) => SPRITES[k].length))
  if (sizes.size !== 1) throw new Error(`terreno con resoluciones mezcladas: ${[...sizes].join(', ')}`)
}

/** Convierte filas ASCII a SVG. `env` aplica recolor y paleta de terreno. */
export interface SvgOptions { size?: number; cssVars?: boolean; className?: string }

export function rowsToRects(rows: string[], env: Environment = ENVIRONMENTS.terrestrial, cssVars = false): string {
  const colorOf = (ch: string) => {
    if (cssVars) return `var(--px-${ch})`
    if (ch in env.terrain) return env.terrain[ch]
    const mapped = env.recolor[ch] ?? ch
    return PALETTE[mapped as PaletteKey]
  }
  const rects: string[] = []
  rows.forEach((row, y) => {
    let x = 0
    while (x < row.length) {
      const ch = row[x]
      if (ch === '.') { x++; continue }
      let w = 1
      while (x + w < row.length && row[x + w] === ch) w++
      rects.push(`<rect x="${x}" y="${y}" width="${w}" height="1" fill="${colorOf(ch)}"/>`)
      x += w
    }
  })
  return rects.join('')
}

/**
 * Lado de la rejilla de un sprite. Todo se deriva de las filas y no de una
 * constante: así conviven sprites de 16 y de 32 mientras dura la migración, y
 * un prop de 2×2 casillas (64 de ancho) tampoco necesita un caso aparte.
 */
export const spriteBox = (rows: string[]) => `0 0 ${rows[0]?.length ?? 0} ${rows.length}`

export function rowsToSvg(rows: string[], env: Environment = ENVIRONMENTS.terrestrial, { size = 16, cssVars = false, className = '' }: SvgOptions = {}): string {
  const cls = className ? ` class="${className}"` : ''
  return `<svg xmlns="http://www.w3.org/2000/svg"${cls} viewBox="${spriteBox(rows)}" width="${size}" height="${size}" shape-rendering="crispEdges">${rowsToRects(rows, env, cssVars)}</svg>`
}

/** Convierte un sprite con nombre a SVG. */
export function toSvg(name: string, env?: Environment, opts?: SvgOptions): string {
  const rows = SPRITES[name]
  if (!rows) throw new Error(`sprite desconocido: ${name}`)
  return rowsToSvg(rows, env, opts)
}

// ─── Autotiling de terreno ───
// La tierra siempre se dibuja entera (las casillas construibles no pierden
// píxeles). La playa vive en los tiles de AGUA que tocan tierra: una franja de
// arena con costa ondulada en cada lado que da a tierra, un bulto redondeado en
// las esquinas diagonales, línea clara contra el pasto y espuma hacia el agua.
// El pasto también asoma 1–2 px de forma irregular dentro de la franja para que
// el límite pasto/arena no sea una recta.
export const TERRAIN_KINDS: TerrainKind[] = ['water', 'land']
/** Lado del tile de terreno en pixeles de arte. */
export const TERRAIN_UNIT = SPRITES.water.length
// Ondulaciones a lo largo de un lado (empiezan y terminan igual para que sean
// continuas entre tiles vecinos). Van a la resolución del tile: al doblarla no
// se duplicó cada valor, se redibujó la onda con el detalle que ahora cabe.
const COAST = [4, 4, 5, 5, 6, 6, 5, 4, 4, 5, 6, 6, 6, 5, 5, 4, 4, 5, 5, 6, 6, 5, 4, 4, 4, 5, 6, 6, 5, 5, 4, 4]
const GRASS = [2, 2, 3, 4, 4, 3, 2, 1, 0, 0, 1, 2, 3, 4, 4, 3, 2, 1, 1, 2, 3, 4, 3, 2, 1, 0, 1, 2, 3, 3, 2, 2]
const BEACH_WIDTH = 6
const CORNER_RADIUS = 9
const SIDES = ['n', 'e', 's', 'w'] as const
const CORNERS: Record<string, [string, string]> = { nw: ['n', 'w'], ne: ['n', 'e'], sw: ['s', 'w'], se: ['s', 'e'] }

type Pixel = 'land' | 'grass' | 'sand' | 'water'

/**
 * Devuelve las filas ASCII del tile `kind` según sus vecinos.
 * `neighbors` = { n, e, s, w, ne, nw, se, sw } con el terreno vecino (agua si falta).
 */
/**
 * Ancho y ondulación de la franja de costa. La playa ancha de la isla tropical
 * no sirve para todos los biomas: el pantano quiere un filo estrecho, no una
 * playa. Cada ambiente puede traer el suyo.
 */
export interface ShoreStyle { width: number; wave: number[]; grass: number[]; corner: number }
export const DEFAULT_SHORE: ShoreStyle = { width: BEACH_WIDTH, wave: COAST, grass: GRASS, corner: CORNER_RADIUS }

export function terrainRows(kind: TerrainKind, neighbors: Neighbors = {}, shore: ShoreStyle = DEFAULT_SHORE): string[] {
  if (kind !== 'water') return SPRITES[kind]
  const land = (k: string) => neighbors[k as keyof Neighbors] === 'land'
  if (![...SIDES, ...Object.keys(CORNERS)].some(land)) return SPRITES.water
  // Lado del tile tomado del propio sprite de terreno: cambiar la resolución es
  // cambiar esas grillas, no perseguir números sueltos por todo el archivo.
  const U = SPRITES.water.length
  const last = U - 1
  const COAST = shore.wave
  const GRASS = shore.grass
  const depth = (i: number) => shore.width + COAST[i % COAST.length]
  const inCorner = (x: number, y: number) => (x + 0.5) ** 2 + (y + 0.5) ** 2 < shore.corner ** 2
  const isGrass = (x: number, y: number): boolean => {
    if (land('n') && y < GRASS[x % GRASS.length]) return true
    if (land('s') && y >= U - GRASS[x % GRASS.length]) return true
    if (land('w') && x < GRASS[y % GRASS.length]) return true
    if (land('e') && x >= U - GRASS[y % GRASS.length]) return true
    return false
  }
  const isSand = (x: number, y: number): boolean => {
    if (land('n') && y < depth(x)) return true
    if (land('s') && y >= U - depth(x)) return true
    if (land('w') && x < depth(y)) return true
    if (land('e') && x >= U - depth(y)) return true
    if (land('nw') && !land('n') && !land('w') && inCorner(x, y)) return true
    if (land('ne') && !land('n') && !land('e') && inCorner(last - x, y)) return true
    if (land('sw') && !land('s') && !land('w') && inCorner(x, last - y)) return true
    if (land('se') && !land('s') && !land('e') && inCorner(last - x, last - y)) return true
    return false
  }
  const inside = (x: number, y: number): Pixel => (isGrass(x, y) ? 'grass' : isSand(x, y) ? 'sand' : 'water')
  // Más allá del borde del tile: tierra, o lo mismo que el píxel del borde.
  const beyond = (x: number, y: number, side: string): Pixel => land(side) ? 'land' : inside(Math.min(last, Math.max(0, x)), Math.min(last, Math.max(0, y)))
  const at = (x: number, y: number): Pixel => {
    if (y < 0) return beyond(x, y, 'n')
    if (y > last) return beyond(x, y, 's')
    if (x < 0) return beyond(x, y, 'w')
    if (x > last) return beyond(x, y, 'e')
    return inside(x, y)
  }
  const rows: string[] = []
  for (let y = 0; y < U; y++) {
    let row = ''
    for (let x = 0; x < U; x++) {
      const pixel = inside(x, y)
      const around = [at(x - 1, y), at(x + 1, y), at(x, y - 1), at(x, y + 1)]
      if (pixel === 'grass') row += '1'
      else if (pixel === 'sand') row += around.includes('land') || around.includes('grass') ? '6' : around.includes('water') ? '7' : '3'
      else row += around.includes('sand') ? '8' : SPRITES.water[y][x]
    }
    rows.push(row)
  }
  return rows
}

/** Declaraciones CSS `--px-X` para un ambiente (usadas con `cssVars: true`). */
export function envCssVars(env: Environment): string {
  const decls: string[] = []
  for (const ch of Object.keys(PALETTE)) {
    const color = ch in env.terrain ? env.terrain[ch] : PALETTE[(env.recolor[ch] ?? ch) as PaletteKey]
    decls.push(`--px-${ch}:${color}`)
  }
  // Los props viven en su propio espacio de nombres.
  for (const [ch, color] of Object.entries(env.props ?? {})) decls.push(`--pp-${ch}:${color}`)
  return decls.join(';')
}

export function toDataUri(name: string, env?: Environment, opts?: SvgOptions): string {
  return `data:image/svg+xml;utf8,${encodeURIComponent(toSvg(name, env, opts))}`
}
